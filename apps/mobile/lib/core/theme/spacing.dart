/// Centralized spacing tokens based on a 4dp base unit.
abstract final class NagrikSpacing {
  static const double space1 = 4.0;
  static const double space2 = 8.0;
  static const double space3 = 12.0;
  static const double space4 = 16.0;
  static const double space5 = 20.0;
  static const double space6 = 24.0;
  static const double space7 = 32.0;
  static const double space8 = 40.0;
  static const double space9 = 48.0;
  static const double space10 = 64.0;

  /// Standard screen-edge padding (16dp).
  static const double screenPadding = space4;

  /// Large section spacing (24dp).
  static const double sectionSpacing = space6;
}
